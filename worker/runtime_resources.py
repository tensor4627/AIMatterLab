"""Fixed standalone worker resource inventory and source contract validation."""
import hashlib
from pathlib import Path

JSON_RESOURCES = frozenset((
    "studio_worker/engine_contracts.json",
    "studio_worker/pygas-editor-hints.json",
))


def worker_files(source):
    """Match desktop/worker-service-version.mjs: POSIX names, UTF-8 byte order."""
    source = Path(source).resolve()
    if not source.is_dir() or not (source / "bootstrap.py").is_file():
        raise ValueError("Worker source unavailable")
    names = []

    def walk(directory):
        for item in directory.iterdir():
            if item.name in ("tests", "__pycache__"):
                continue
            if item.is_symlink():
                raise ValueError("Linked worker source refused")
            if item.is_dir():
                walk(item)
            elif item.is_file():
                name = item.relative_to(source).as_posix()
                if item.suffix in (".py", ".toml") or name in JSON_RESOURCES:
                    names.append(name)

    walk(source)
    return sorted(names, key=lambda value: value.encode("utf-8"))


def verify_tool_contract(source):
    """Check generated bytes in a checkout; standalone workers need only local bytes."""
    source = Path(source).resolve()
    resource = source / "studio_worker" / "engine_contracts.json"
    if not resource.is_file() or resource.is_symlink():
        raise ValueError("Standalone worker tool contract unavailable")
    canonical = source.parent / "contracts" / "tools" / "engine-contracts.json"
    if canonical.exists():
        if canonical.is_symlink() or not canonical.is_file() or canonical.read_bytes() != resource.read_bytes():
            raise ValueError("Generated worker tool contract is stale; run node scripts/sync-tool-contracts.mjs")


def runtime_identity(source, names):
    source = Path(source).resolve()
    digest = hashlib.sha256()
    for name in names:
        digest.update(name.encode("utf-8"))
        digest.update((source / name).read_bytes())
    return digest.hexdigest()[:20]
